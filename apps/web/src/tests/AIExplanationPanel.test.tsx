/**
 * Unit & Integration Tests for AIExplanationPanel Component
 * Strictly adheres to 01_SHARED_TYPES.md, 04_API_SPEC.md, 05_AI_CONTRACTS.md, and 08_UI_DATA_CONTRACT.md.
 *
 * Dev B — Step 4:
 * Covers all 12 minimum requirements for AIExplanationPanel:
 * 1. Prediction card renders
 * 2. Analytical reasoning renders
 * 3. Model version renders
 * 4. model_run_id renders
 * 5. Contributing features render
 * 6. Model link probability renders separately
 * 7. Mandatory GATv2 disclaimer renders exactly
 * 8. No accusatory/guilt/criminality terminology is introduced
 * 9. GNN offline state disables prediction functionality appropriately
 * 10. Classical SNA/rules alerts remain available
 * 11. LLM offline state uses deterministic fallback explanation
 * 12. No fabricated prediction/explanation is displayed
 */

import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import {
  AIExplanationPanel,
  MANDATORY_GATV2_DISCLAIMER,
  DETERMINISTIC_FALLBACK_EXPLANATION,
} from '../components/panels/AIExplanationPanel';
import { CaseProvider } from '../context/CaseContext';
import { SelectionProvider, useSelection } from '../context/SelectionContext';

describe('AIExplanationPanel Component Tests', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  // 1. Prediction card renders
  it('1. renders prediction card and association header', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    expect(screen.getByTestId('ai-explanation-panel')).toBeInTheDocument();
    expect(screen.getByTestId('ai-explanation-title')).toHaveTextContent('AI Explanation & Link Predictions');
    expect(screen.getByTestId('prediction-card-pred-001-gat-tariq-rajesh')).toBeInTheDocument();
    expect(screen.getByText('Tariq Khan')).toBeInTheDocument();
    expect(screen.getByText('Rajesh Gupta')).toBeInTheDocument();
    expect(screen.getByText('KNOWS')).toBeInTheDocument();
  });

  // 2. Analytical reasoning renders
  it('2. renders analytical reasoning for predicted unobserved association', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const reasoning = screen.getByTestId('analytical-reasoning');
    expect(reasoning).toHaveTextContent(
      /High structural similarity via shared financial transaction path/i
    );
    expect(reasoning).toHaveTextContent(/co-located mobile tower activity/i);
  });

  // 3. Model version renders
  it('3. renders model architecture name and version metadata', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const versionMeta = screen.getByTestId('model-version');
    expect(versionMeta).toHaveTextContent('GATv2-Supervised-LinkPredictor (v1.4.0)');
  });

  // 4. model_run_id renders
  it('4. renders versioned model_run_id tracking identifier', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const runIdMeta = screen.getByTestId('model-run-id');
    expect(runIdMeta).toHaveTextContent('run-gatv2-20260215-01');
  });

  // 5. Contributing features render
  it('5. renders distinct contributing feature signals without collapsing semantics', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    expect(screen.getByTestId('feature-degree')).toHaveTextContent('0.75');
    expect(screen.getByTestId('feature-betweenness')).toHaveTextContent('0.88');
    expect(screen.getByTestId('feature-temporal-activity')).toHaveTextContent('0.65');
    expect(screen.getByTestId('feature-observation-frequency')).toHaveTextContent('14');
    expect(screen.getByTestId('feature-relationship-belief')).toHaveTextContent('0.72');
  });

  // 6. Model link probability renders separately
  it('6. displays model link probability distinctly as numeric value between 0.0 and 1.0', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const probElement = screen.getByTestId('model-link-probability');
    expect(probElement).toHaveTextContent('0.84');
    expect(screen.getByText('Model Link Probability')).toBeInTheDocument();

    // Verify it is NOT labeled as guilt or crime score
    expect(screen.queryByText(/guilt/i)).not.toBeInTheDocument();
  });

  // 7. Mandatory GATv2 disclaimer renders exactly
  it('7. renders mandatory GATv2 disclaimer verbatim', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const disclaimer = screen.getByTestId('gatv2-mandatory-disclaimer');
    expect(disclaimer.textContent?.trim()).toBe(MANDATORY_GATV2_DISCLAIMER);
    expect(disclaimer).toHaveTextContent(
      'Inferred link generated by GATv2 model — requires human investigator corroboration. Priority scores represent investigative leads and do not constitute moral or legal proof.'
    );
  });

  // 8. No accusatory / guilt / criminality terminology
  it('8. strictly adheres to non-accusatory invariant: no guilt, crime certainty, or kingpin terms', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel />
      </CaseProvider>
    );

    const panelText = screen.getByTestId('ai-explanation-panel').textContent?.toLowerCase() || '';

    expect(panelText).not.toContain('guilt probability');
    expect(panelText).not.toContain('crime probability');
    expect(panelText).not.toContain('kingpin detection');
    expect(panelText).not.toContain('guilt score');
    expect(panelText).not.toContain('proof of criminality');
  });

  // 9. GNN offline state disables prediction functionality appropriately
  it('9. handles GNN offline state: renders offline warning and disables prediction actions', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel gnnStatus="OFFLINE" />
      </CaseProvider>
    );

    expect(screen.getByTestId('gnn-status-indicator')).toHaveTextContent('GNN: OFFLINE');
    expect(screen.getByTestId('gnn-offline-banner')).toHaveTextContent(/GNN Inference Engine Offline/i);

    const focusBtn = screen.getByTestId('focus-prediction-btn');
    expect(focusBtn).toBeDisabled();
    expect(focusBtn).toHaveTextContent('GNN Offline — Prediction Disabled');
  });

  // 10. Classical SNA / rules alerts remain available during GNN offline
  it('10. keeps classical SNA metrics and deterministic rules alerts active even when GNN is offline', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel gnnStatus="OFFLINE" />
      </CaseProvider>
    );

    // Classical SNA section remains fully available
    const snaSection = screen.getByTestId('classical-sna-section');
    expect(snaSection).toBeInTheDocument();
    expect(snaSection).toHaveTextContent(/Classical SNA Metrics/i);
    expect(snaSection).toHaveTextContent('Degree: 0.75');
    expect(snaSection).toHaveTextContent('Betweenness: 0.88');

    // Rules alerts section remains available
    const rulesAlerts = screen.getByTestId('rules-alerts-count');
    expect(rulesAlerts).toHaveTextContent('2 Active');
  });

  // 11. LLM offline state uses deterministic fallback explanation
  it('11. handles LLM offline state: falls back to deterministic template explanation with indicator', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel llmStatus="OFFLINE" />
      </CaseProvider>
    );

    expect(screen.getByTestId('llm-fallback-indicator')).toBeInTheDocument();
    expect(screen.getByTestId('llm-fallback-indicator')).toHaveTextContent(
      /Deterministic Fallback Explanation — LLM Offline/i
    );

    const reasoning = screen.getByTestId('analytical-reasoning');
    expect(reasoning).toHaveTextContent(DETERMINISTIC_FALLBACK_EXPLANATION);
    expect(reasoning).toHaveTextContent(
      'Deterministic Template Fallback: Link predicted based on topological graph structure'
    );
  });

  // 12. No fabricated prediction / explanation is displayed
  it('12. displays empty state when predictions array is empty without fabricating data', () => {
    render(
      <CaseProvider>
        <AIExplanationPanel predictions={[]} />
      </CaseProvider>
    );

    expect(screen.getByTestId('empty-predictions-message')).toHaveTextContent(
      'No link predictions currently available for this case.'
    );
    expect(screen.queryByTestId('model-link-probability')).not.toBeInTheDocument();
  });

  // Integration: Tab switching & Focus Prediction on Canvas
  it('handles switching tabs and Focus Prediction on Canvas', () => {
    const handleFocus = vi.fn();

    const Harness = () => {
      const { selectedNode } = useSelection();
      return (
        <div>
          <span data-testid="active-selected-node">{selectedNode?.id ?? 'none'}</span>
          <AIExplanationPanel onFocusPrediction={handleFocus} />
        </div>
      );
    };

    render(
      <CaseProvider>
        <SelectionProvider>
          <Harness />
        </SelectionProvider>
      </CaseProvider>
    );

    // Switch tab to prediction 2
    const tab2 = screen.getByTestId('tab-pred-002-gat-phone2-phone3');
    fireEvent.click(tab2);

    expect(screen.getByTestId('prediction-card-pred-002-gat-phone2-phone3')).toBeInTheDocument();
    expect(screen.getByTestId('model-link-probability')).toHaveTextContent('0.76');

    // Click Focus on Canvas
    const focusBtn = screen.getByTestId('focus-prediction-btn');
    fireEvent.click(focusBtn);

    expect(handleFocus).toHaveBeenCalledWith(
      expect.objectContaining({ prediction_id: 'pred-002-gat-phone2-phone3' })
    );
    // Node phone-2 selected via SelectionContext
    expect(screen.getByTestId('active-selected-node')).toHaveTextContent('node-phone-2');
  });
});
